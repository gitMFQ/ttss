var speakableTextRe = regexp.MustCompile(`[\p{L}\p{N}]`)

func hasSpeakableText(text string) bool {
	return speakableTextRe.MatchString(text)
}

func silentMP3Audio() []byte {
	return append([]byte(nil), silentMP3...)
}
